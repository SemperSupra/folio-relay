#!/usr/bin/env python3
"""Reproducible nonmutating Thai OCR parameter sweep on synthetic raster pages.

All inputs are generated by scripts/ci/generate-paperless-en-de-th.py.
This compares direct Tesseract CLI with multiple language orders and PSMs,
NOT the complete Paperless/OCRmyPDF ingestion path. A result does not grant
permission to rewrite Paperless documents or automatically assign metadata.
"""
from __future__ import annotations

import json
import pathlib
import subprocess
import sys
import unicodedata

LANGUAGE_ORDERS = ("eng+deu+tha", "tha+eng+deu", "tha")
PSMS = (3, 6)
THAI_START = 0x0E00
THAI_END = 0x0E7F


def chars(text: str) -> str:
    """Thai-only Unicode NFC projection for evaluation, not stored text."""
    return "".join(
        c for c in unicodedata.normalize("NFC", text)
        if THAI_START <= ord(c) <= THAI_END
    )


def edit_distance(a: str, b: str) -> int:
    if len(a) > len(b):
        a, b = b, a
    prev = list(range(len(a) + 1))
    for y, letter_b in enumerate(b, 1):
        curr = [y]
        for x, letter_a in enumerate(a, 1):
            curr.append(min(
                curr[-1] + 1, prev[x] + 1,
                prev[x-1] + (letter_a != letter_b)
            ))
        prev = curr
    return prev[-1]


def main() -> int:
    root = pathlib.Path(sys.argv[1])
    all_cases = json.loads((root / "classification-manifest.json").read_text("utf-8"))
    # Keep all six positive and two negated Thai classifications, plus the
    # mixed-script scan; no real-user data, no archived PDFs or external APIs.
    cases = [x for x in all_cases if x["language"] == "th"]
    one_mixed = next(x for x in json.loads((root / "manifest.json").read_text("utf-8"))
                     if x["id"] == "mixed")
    cases.append(dict(one_mixed, negative=False, kind="mixed"))
    if len(cases) != 9:
        raise ValueError("Expected 6 Thai positives + 2 negations + mixed scan")
    report = []
    for order in LANGUAGE_ORDERS:
        for psm in PSMS:
            rows = []
            for item in cases:
                source = root / item["file"]
                if not source.is_file():
                    raise ValueError("missing generated raster case")
                result = subprocess.run(
                    ["tesseract", str(source), "stdout", "-l", order,
                     "--psm", str(psm)],
                    text=True, capture_output=True, timeout=90, check=True
                )
                truth = chars(" ".join(item["lines"]))
                output = chars(result.stdout)
                if not truth:
                    raise ValueError("Synthetic Thai reference not rendered")
                distance = edit_distance(truth, output)
                rows.append({
                    "id": item["id"],
                    "negative": bool(item.get("negative", False)),
                    "truth_chars": len(truth),
                    "recognized_chars": len(output),
                    "edit_distance": distance,
                    "cer": round(distance / len(truth), 4),
                })
            total_truth = sum(r["truth_chars"] for r in rows)
            total_edit = sum(r["edit_distance"] for r in rows)
            report.append({
                "languages": order,
                "psm": psm,
                "corpus": len(rows),
                "thai_character_error_rate": round(total_edit / total_truth, 4),
                "th_only_cases": sum(r["id"] != "mixed" for r in rows),
                "mixed_cases": 1,
                "rows": rows,
            })
    if len(report) != 6:
        raise AssertionError("Expected all six OCR configurations")
    # Sort for audit rather than choosing a setting based on one best case.
    best = sorted(report, key=lambda r: (r["thai_character_error_rate"],
                                          r["languages"], r["psm"]))[0]
    print("FOLIO_THAI_TESSERACT_SWEEP=" + json.dumps(
        {"source": "synthetic generated PNG",
         "kind": "direct-tesseract-not-paperless",
         "mode": "evaluation-only",
         "profiles": report,
         "lowest_aggregate_cer": {
             "languages": best["languages"],
             "psm": best["psm"],
             "thai_character_error_rate": best["thai_character_error_rate"]
         }}, ensure_ascii=False, separators=(",", ":")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
