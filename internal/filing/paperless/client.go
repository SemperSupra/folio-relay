// Package paperless is a deliberately narrow, opt-in adapter to the official
// Paperless-ngx REST API. Paperless remains the records/metadata authority.
// There are NO FolioRelay App hooks or live target endpoints in this package.
package paperless

import (
 "bytes"
 "context"
 "crypto/sha256"
 "encoding/hex"
 "encoding/json"
 "errors"
 "fmt"
 "io"
 "mime/multipart"
 "net"
 "net/http"
 "net/url"
 "regexp"
 "strings"
 "time"
)

const MaxDocumentBytes = 24 << 20

var (
 ErrInvalid = errors.New("invalid paperless request")
 ErrRemote = errors.New("paperless response failed")
 ErrUncertain = errors.New("paperless outcome must be reconciled")
 uuidRe = regexp.MustCompile(`(?i)^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$`)
 shaRe = regexp.MustCompile(`^[a-f0-9]{64}$`)
)

type Config struct {
 // BaseURL is a previously approved operator configuration, never a value
 // extracted from document text or generated by an LLM.
 BaseURL string
 Token string
 // TestOnlyLoopbackHTTP permits httptest or a disposable loopback fixture.
 // Never enable on a TrueNAS installation or a user-facing settings API.
 TestOnlyLoopbackHTTP bool
}

type Client struct {
 endpoint string
 token string
 httpClient http.Client
}

func NewClient(cfg Config, transport *http.Client) (*Client,error) {
 u,err:=url.Parse(cfg.BaseURL)
 if err!=nil || u.Host=="" || u.User!=nil || u.RawQuery!="" || u.Fragment!="" ||
    u.Path!="" && u.Path!="/" || strings.Contains(u.Host,"%") {
    return nil,ErrInvalid
 }
 if len(cfg.Token)<8 || strings.ContainsAny(cfg.Token,"\r\n") {
    return nil,ErrInvalid
 }
 if u.Scheme!="https" {
    hostname:=u.Hostname()
    ip:=net.ParseIP(hostname)
    if !cfg.TestOnlyLoopbackHTTP || u.Scheme!="http" ||
       !((ip!=nil && ip.IsLoopback()) || strings.EqualFold(hostname,"localhost")) {
       return nil,ErrInvalid
    }
 }
 client:=http.Client{Timeout:20*time.Second}
 if transport!=nil {
    client=*transport
    if client.Timeout==0 {client.Timeout=20*time.Second}
 }
 // Never follow a redirect with an authorization token. The configured
 // scheme/host is the complete allowed destination for this source slice.
 client.CheckRedirect=func(*http.Request,[]*http.Request)error{return http.ErrUseLastResponse}
 return &Client{endpoint:strings.TrimRight(u.String(),"/"),token:cfg.Token,httpClient:client},nil
}

func (c *Client) do(ctx context.Context,method,uri,mime string,body io.Reader)(*http.Response,error) {
 if c==nil {return nil,ErrInvalid}
 req,err:=http.NewRequestWithContext(ctx,method,c.endpoint+uri,body)
 if err!=nil{return nil,err}
 req.Header.Set("Authorization","Token "+c.token)
 req.Header.Set("Accept","application/json; version=10")
 if mime!="" {req.Header.Set("Content-Type",mime)}
 resp,err:=c.httpClient.Do(req)
 if err!=nil {
   // The server may already have accepted an upload before transport fails.
   // All external writes must be preceded by a durable reservation.
   return nil,fmt.Errorf("%w: transport result not definitive",ErrUncertain)
 }
 if resp.StatusCode <200 || resp.StatusCode >=300 {
   resp.Body.Close()
   // A proxy 5xx/redirect/429 after POST is not definitive proof of no
   // side effect. The durable submission reservation must stay HOLD.
   if method==http.MethodPost && (resp.StatusCode>=500 || resp.StatusCode==429 || resp.StatusCode>=300 && resp.StatusCode<400) {
      return nil,fmt.Errorf("%w: HTTP %d",ErrUncertain,resp.StatusCode)
   }
   return nil,fmt.Errorf("%w: HTTP %d",ErrRemote,resp.StatusCode)
 }
 return resp,nil
}

type Document struct {
 Content []byte
 SHA256 string
 MediaType string
}
func (d Document) validate() (string,error) {
 if len(d.Content)==0 || len(d.Content)>MaxDocumentBytes ||
    !shaRe.MatchString(d.SHA256) {return "",ErrInvalid}
 h:=sha256.Sum256(d.Content)
 if hex.EncodeToString(h[:])!=d.SHA256{return "",ErrInvalid}
 switch d.MediaType {
 case "application/pdf":return ".pdf",nil
 case "image/png":return ".png",nil
 case "image/jpeg":return ".jpg",nil
 case "image/tiff":return ".tif",nil
 default:return "",ErrInvalid
 }
}

// Upload consumes immutable, locally-validated bytes. It deliberately passes
// NO title/tags/path or LLM suggestions: Paperless native rules/ML/LLM decide.
// Returned UUID means queued, never successfully archived.
func (c *Client) Upload(ctx context.Context,d Document)(string,error) {
 suffix,err:=d.validate()
 if err!=nil{return "",err}
 var buf bytes.Buffer
 writer:=multipart.NewWriter(&buf)
 part,err:=writer.CreateFormFile("document","scan-"+d.SHA256[:16]+suffix)
 if err!=nil{return "",err}
 if _,err=part.Write(d.Content);err!=nil{return "",err}
 if err=writer.Close();err!=nil{return "",err}
 resp,err:=c.do(ctx,http.MethodPost,"/api/documents/post_document/",writer.FormDataContentType(),&buf)
 if err!=nil{return "",err}
 defer resp.Body.Close()
 limited:=io.LimitReader(resp.Body,4096)
 var uuid string
 if err=json.NewDecoder(limited).Decode(&uuid);err!=nil||!uuidRe.MatchString(uuid) {
    // A 2xx with malformed body cannot be treated as safe to retry.
    return "",ErrUncertain
 }
 return uuid,nil
}

type Task struct {
 TaskID string
 Status string
 DocumentID int
 DuplicateOf int
 // Outcome is pending, archived, duplicate, rejected, or unknown.
 Outcome string
}

// Observe is read-only. Its query and parser match Paperless API v10
// introduced in the 3.1.3 catalog release; older versions need a new adapter.
func (c *Client) Observe(ctx context.Context,taskID string)(Task,error) {
 if !uuidRe.MatchString(taskID) {return Task{},ErrInvalid}
 uri:="/api/tasks/?task_id="+url.QueryEscape(taskID)
 resp,err:=c.do(ctx,http.MethodGet,uri,"",nil)
 if err!=nil{return Task{},err}
 defer resp.Body.Close()
 var out struct {
   Count int `json:"count"`
   Results []struct {
     TaskID string `json:"task_id"`
     Status string `json:"status"`
     ResultData struct {
       DocumentID int `json:"document_id"`
       DuplicateOf int `json:"duplicate_of"`
     } `json:"result_data"`
   } `json:"results"`
 }
 if err:=json.NewDecoder(io.LimitReader(resp.Body,1<<20)).Decode(&out);err!=nil {return Task{},ErrUncertain}
 if out.Count==0 && len(out.Results)==0 {
    // Task may still be unobserved or invisible to the token's permissions.
    return Task{TaskID:taskID,Outcome:"unknown"},nil
 }
 if out.Count!=1 || len(out.Results)!=1 || out.Results[0].TaskID!=taskID {
    return Task{},ErrUncertain
 }
 r:=out.Results[0]
 task:=Task{TaskID:taskID,Status:r.Status,DocumentID:r.ResultData.DocumentID,DuplicateOf:r.ResultData.DuplicateOf}
 // Paperless v3.1.3 API v10 serializes lowercase model statuses.
 // Older v9 Celery uppercase states must not silently be mistaken for v10.
 switch r.Status {
 case "pending","started":
    task.Outcome="pending"
 case "success":
    switch {
    case task.DocumentID>0 && task.DuplicateOf==0: task.Outcome="archived"
    case task.DuplicateOf>0 && task.DocumentID==0: task.Outcome="duplicate"
    default: task.Outcome="unknown"
    }
 case "failure","revoked":
    task.Outcome="rejected"
 default:
    task.Outcome="unknown"
 }
 return task,nil
}

// Record is read-only evidence of Paperless' own metadata after consumption.
// All taxonomy assignment and updates remain owned by Paperless-native flows.
type Record struct {
 ID int `json:"id"`
 Title string `json:"title"`
 Correspondent *int `json:"correspondent"`
 DocumentType *int `json:"document_type"`
 StoragePath *int `json:"storage_path"`
 Tags []int `json:"tags"`
 Created string `json:"created"`
}
func (c *Client) ReadRecord(ctx context.Context,id int)(Record,error) {
 if id<=0{return Record{},ErrInvalid}
 resp,err:=c.do(ctx,http.MethodGet,fmt.Sprintf("/api/documents/%d/",id),"",nil)
 if err!=nil{return Record{},err}
 defer resp.Body.Close()
 var record Record
 if err:=json.NewDecoder(io.LimitReader(resp.Body,1<<20)).Decode(&record);err!=nil{return Record{},ErrUncertain}
 if record.ID!=id{return Record{},ErrUncertain}
 return record,nil
}
